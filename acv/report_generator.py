"""Generate a publishable Markdown report from structured review findings."""

from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Iterable

from .reviewer import ReviewIssue


def _inline(value: object) -> str:
    return str(value).replace("`", "\\`").replace("\n", " ").strip()


def render_report(
    *,
    project_path: str | Path,
    files_analyzed: int,
    issues: Iterable[ReviewIssue],
    warnings: Iterable[str] = (),
) -> str:
    issue_list = list(issues)
    warning_list = list(warnings)
    project = Path(project_path)
    counts = Counter(issue.severity for issue in issue_list)

    lines = [
        "# ACV Code Validation Report",
        "",
        "## Project Summary",
        "",
        f"- **Project:** `{_inline(project.name)}`",
        f"- **Path:** `{_inline(project)}`",
        f"- **Files analyzed:** {files_analyzed}",
        f"- **Issues found:** {len(issue_list)}",
    ]

    if issue_list:
        severity_summary = ", ".join(
            f"{name.title()}: {counts[name]}"
            for name in ("critical", "high", "medium", "low", "info")
            if counts[name]
        )
        lines.append(f"- **Severity summary:** {severity_summary}")

    if warning_list:
        lines.extend(["", "### Analysis Warnings", ""])
        lines.extend(f"- {_inline(warning)}" for warning in warning_list)

    lines.extend(["", "## Review Results", ""])
    if not issue_list:
        lines.extend(
            [
                "No meaningful code-review issues were identified in the analyzed files.",
                "This result is not a guarantee that the project is defect-free; automated review should complement testing and human review.",
            ]
        )
    else:
        for number, issue in enumerate(issue_list, start=1):
            lines.extend(
                [
                    f"### {number}. [{issue.severity.upper()}] {_inline(issue.problem)}",
                    "",
                    f"- **Severity:** {issue.severity.title()}",
                    f"- **Category:** {_inline(issue.category)}",
                    f"- **File:** `{_inline(issue.file)}`",
                    f"- **Location:** {_inline(issue.location)}",
                    "",
                    "**Problem**",
                    "",
                    issue.problem.strip(),
                    "",
                    "**Why it matters**",
                    "",
                    issue.reason.strip(),
                    "",
                    "**Recommended improvement**",
                    "",
                    issue.suggestion.strip(),
                    "",
                ]
            )

    lines.extend(["---", "", "Generated by ACV v0.2 (classic review mode).", ""])
    return "\n".join(lines)


def write_report(
    output_path: str | Path,
    *,
    project_path: str | Path,
    files_analyzed: int,
    issues: Iterable[ReviewIssue],
    warnings: Iterable[str] = (),
) -> Path:
    destination = Path(output_path).expanduser()
    try:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(
            render_report(
                project_path=project_path,
                files_analyzed=files_analyzed,
                issues=issues,
                warnings=warnings,
            ),
            encoding="utf-8",
        )
    except OSError as exc:
        raise OSError(f"Could not write report to {destination}: {exc}") from exc
    return destination.resolve()
