"""Markdown reporting for evidence gathered by the ACV reviewer agent."""

from __future__ import annotations

from pathlib import Path
from typing import Iterable

from .review_agent import AgentIssue, AgentReviewResult


def _inline(value: object) -> str:
    return str(value).replace("`", "\\`").replace("\n", " ").strip()


def _render_issue(lines: list[str], number: int, issue: AgentIssue) -> None:
    confidence = "Needs verification" if issue.confidence == "possible" else "Confirmed"
    lines.extend(
        [
            f"### {number}. [{issue.severity.upper()}] {_inline(issue.problem)}",
            "",
            f"- **Severity:** {issue.severity.title()}",
            f"- **Category:** {_inline(issue.category)}",
            f"- **Confidence:** {confidence}",
            f"- **File:** `{_inline(issue.file)}`",
            f"- **Location:** {_inline(issue.location)}",
            "",
            "**Problem**",
            "",
            issue.problem.strip(),
            "",
            "**Evidence**",
            "",
            issue.evidence.strip(),
            "",
            "**Why it matters**",
            "",
            issue.why_it_matters.strip(),
            "",
            "**Suggested improvement**",
            "",
            issue.suggested_improvement.strip(),
            "",
        ]
    )


def _issue_groups(issues: Iterable[AgentIssue]) -> list[tuple[str, list[AgentIssue]]]:
    groups: dict[str, list[AgentIssue]] = {
        "Critical / High Priority Issues": [],
        "Other Issues": [],
        "Performance / Architecture Suggestions": [],
        "Possible Issues Requiring Verification": [],
    }
    for issue in issues:
        category = issue.category.lower()
        if issue.confidence == "possible":
            group = "Possible Issues Requiring Verification"
        elif issue.severity in {"critical", "high"}:
            group = "Critical / High Priority Issues"
        elif "performance" in category or "architecture" in category:
            group = "Performance / Architecture Suggestions"
        else:
            group = "Other Issues"
        groups[group].append(issue)
    return list(groups.items())


def render_agent_report(result: AgentReviewResult) -> str:
    """Render the stable v0.2 report structure from validated agent data."""
    languages = ", ".join(result.languages) if result.languages else "Unknown"
    lines = [
        "# ACV Review Report",
        "",
        "## Project Summary",
        "",
        f"- **Project:** `{_inline(result.project_path.name)}`",
        f"- **Path:** `{_inline(result.project_path)}`",
        f"- **Project type:** {_inline(result.project_type)}",
        f"- **Main languages:** {_inline(languages)}",
        f"- **Source files discovered:** {result.files_discovered}",
        f"- **Files actually inspected:** {len(result.files_inspected)}",
        f"- **Agent steps used:** {result.steps_used}",
        f"- **Issues found:** {len(result.issues)}",
    ]

    if result.warnings:
        lines.extend(["", "### Review Warnings", ""])
        lines.extend(f"- {_inline(warning)}" for warning in result.warnings)

    lines.extend(["", "## Files Inspected", ""])
    if result.files_inspected:
        lines.extend(f"- `{_inline(path)}`" for path in result.files_inspected)
    else:
        lines.append("No source file contents were read before the review stopped.")

    issue_number = 1
    for heading, issues in _issue_groups(result.issues):
        lines.extend(["", f"## {heading}", ""])
        if not issues:
            lines.append("No evidence-backed findings in this category.")
            continue
        for issue in issues:
            _render_issue(lines, issue_number, issue)
            issue_number += 1

    lines.extend(
        [
            "",
            "---",
            "",
            "Generated by ACV v0.2 Reviewer Agent (read-only).",
            "Only files listed under **Files Inspected** were read directly by the agent.",
            "",
        ]
    )
    return "\n".join(lines)


def write_agent_report(output_path: str | Path, result: AgentReviewResult) -> Path:
    destination = Path(output_path).expanduser()
    try:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(render_agent_report(result), encoding="utf-8")
    except OSError as exc:
        raise OSError(f"Could not write report to {destination}: {exc}") from exc
    return destination.resolve()
